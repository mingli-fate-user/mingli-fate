function getGuaCi(guaName: string): string {
  return GUA_CI[guaName] || '阴阳变化，吉凶存乎一心。';
}

export function calculateHuangJi(year: number, month: number, day: number, hour: number): HuangJiResult {
  // 简化算法：用出生时间推卦
  const total = year + month + day + hour;
  const xianTianIdx = total % 64;
  const houTianIdx = (total * 7 + month * 3) % 64;
  const daYunIdx = (total * 13 + day * 5) % 64;

  const xianTianGua = GUA_NAMES[xianTianIdx] || GUA_NAMES[0];
  const houTianGua = GUA_NAMES[houTianIdx] || GUA_NAMES[0];
  const daYunGua = GUA_NAMES[daYunIdx] || GUA_NAMES[0];

  // 元会运世（简化）
  const yuanIdx = Math.floor((year - 1) / 10800) % 12;
  const huiIdx = Math.floor((year - 1) / 360) % 30;
  const yunIdx = Math.floor((year - 1) / 12) % 12;
  const shiIdx = (year - 1) % 12;

  const yuanNames = ['子元', '丑元', '寅元', '卯元', '辰元', '巳元', '午元', '未元', '申元', '酉元', '戌元', '亥元'];
  const huiNames = ['天开于子', '地辟于丑', '人生于寅', '物茂于卯', '功收于辰', '气藏于巳', '阳极于午', '阴生于未', '肃杀于申', '收敛于酉', '闭藏于戌', '归元于亥', '复始', '长养', '茂盛', '华实', '收藏', '闭蛰', '发陈', '蕃茂', '容平', '闭藏', '发生', '阳和', '炎暑', '凉肃', '寒凛', '温生', '阳明', '少阳'];

  return {
    birthYear: year,
    birthMonth: month,
    birthDay: day,
    birthHour: hour,
    xianTianGua,
    houTianGua,
    daYunGua,
    yuan: yuanNames[yuanIdx] || '子元',
    hui: huiNames[huiIdx] || '天开于子',
    yun: `第${yunIdx + 1}运`,
    shi: `第${shiIdx + 1}世`,
    yaoCi: `以${xianTianGua}之体，应${houTianGua}之用。`,
    guaCi: getGuaCi(xianTianGua),
  };
}
