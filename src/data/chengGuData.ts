// 时辰映射（24小时制 → 时辰名）
export function getShiChenName(hour: number): string {
  if (hour >= 23 || hour < 1) return '子';
  if (hour < 3) return '丑';
  if (hour < 5) return '寅';
  if (hour < 7) return '卯';
  if (hour < 9) return '辰';
  if (hour < 11) return '巳';
  if (hour < 13) return '午';
  if (hour < 15) return '未';
  if (hour < 17) return '申';
  if (hour < 19) return '酉';
  if (hour < 21) return '戌';
  return '亥';
}

// 将总钱数转换为 几两几钱
export function formatWeight(totalQian: number): string {
  const liang = Math.floor(totalQian / 10);
  const qian = totalQian % 10;
  return `${liang}两${qian}钱`;
}

// 将总钱数转为数字（两.钱的格式，用于查表）
export function weightToNumber(totalQian: number): string {
  const liang = Math.floor(totalQian / 10);
  const qian = totalQian % 10;
  return `${liang}.${qian}`;
}

