// 查找最接近的歌诀（因为不是所有重量都有精确匹配）
export function findPoem(weightNum: string, gender: '男' | '女') {
  const poems = gender === '男' ? MALE_POEMS : FEMALE_POEMS;
  // 先精确匹配
  if (poems[weightNum]) return { weight: weightNum, ...poems[weightNum] };
  // 否则找最接近的
  const weights = Object.keys(poems).map(Number).sort((a, b) => a - b);
  const target = Number(weightNum);
  let closest = weights[0];
  for (const w of weights) {
    if (Math.abs(w - target) < Math.abs(closest - target)) {
      closest = w;
    }
  }
  const closestStr = closest.toFixed(1);
  return { weight: closestStr, ...poems[closestStr] };
}
