function getGuaCi(num: number): string {
  return GUA_CI[num] || '阴阳变化，吉凶存乎一心。静以修身，俭以养德。';
}

export function castLingQiJing(): LingQiResult {
  // 模拟三投十二棋
  // 每投4棋，按阴阳面数 1-4
  const upper = Math.floor(Math.random() * 4) + 1;
  const middle = Math.floor(Math.random() * 4) + 1;
  const lower = Math.floor(Math.random() * 4) + 1;
  const total = upper + middle + lower;

  // 卦号根据三投结果计算 (简化)
  const guaNumber = ((upper - 1) * 16 + (middle - 1) * 4 + (lower - 1)) % 125 + 1;

  const yinYangMap: Record<number, string> = {
    1: '一阳', 2: '二阳', 3: '三阴', 4: '四阴',
  };

  return {
    upper,
    middle,
    lower,
    total,
    guaNumber,
    guaName: GUA_NAMES[guaNumber] || '灵卦',
    guaCi: getGuaCi(guaNumber),
    yinYang: `${yinYangMap[upper]}·${yinYangMap[middle]}·${yinYangMap[lower]}`,
  };
}
